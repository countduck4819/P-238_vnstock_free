"""Human-operated review helper; it never calls the section parser."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GT = ROOT / "financial_ocr_mvp/output/phase4_manual_ground_truth.json"
KEYWORDS = ("KIỂM TOÁN", "BẢNG CÂN ĐỐI", "TÌNH HÌNH TÀI CHÍNH", "KẾT QUẢ HOẠT ĐỘNG KINH DOANH", "LƯU CHUYỂN TIỀN TỆ", "THUYẾT MINH")
SECTIONS = ("audit_report", "balance_sheet", "income_statement", "cash_flow", "notes")
MARKER = re.compile(r"^\s*=+\s*PAGE\s+(\d+)\s*=+\s*$", re.I | re.M)


def pages(text: str) -> list[dict[str, object]]:
    matches = list(MARKER.finditer(text)); result=[]
    for i, match in enumerate(matches):
        body=text[match.end():(matches[i+1].start() if i+1<len(matches) else len(text))]
        lines=[line.strip() for line in body.splitlines() if line.strip()]
        highlights=[line for line in lines if any(k in line.upper() for k in KEYWORDS)]
        result.append({"page":int(match.group(1)),"first_meaningful_lines":lines[:20],"table_count":len(re.findall(r"<table\b",body,re.I)),"highlight_lines":highlights[:10]})
    return result


def validate_section(value: object, available: set[int]) -> dict[str, object] | None:
    if value is None or value == "none": return None
    if not isinstance(value, dict): raise ValueError("section phải là null hoặc object")
    selected=sorted(set(int(x) for x in value.get("pages", [])))
    if not selected or any(x not in available for x in selected): raise ValueError("section chứa page không tồn tại")
    if selected != list(range(selected[0],selected[-1]+1)): raise ValueError("pages phải là một range liên tục")
    return {"pages":selected,"start_page":selected[0],"end_page":selected[-1],"start_heading":value.get("start_heading",""),"review_notes":value.get("review_notes","")}


def display(document_id: str) -> None:
    records=json.loads(GT.read_text(encoding="utf-8")); record=next((x for x in records if x["document_id"]==document_id),None)
    if not record: raise SystemExit(f"Không tìm thấy document_id: {document_id}")
    path=Path(record["normalized_path"]); actual=hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != record["normalized_sha256"]: raise SystemExit("DOCUMENT_NOT_RESOLVED: normalized SHA mismatch")
    print(json.dumps({"document_id":document_id,"ticker":record["ticker"],"year":record["year"],"page_count":len(pages(path.read_text(encoding='utf-8',errors='replace'))),"pages":pages(path.read_text(encoding='utf-8',errors='replace'))},ensure_ascii=False,indent=2))


def save(document_id: str, labels_path: Path, status: str) -> None:
    records=json.loads(GT.read_text(encoding="utf-8")); record=next((x for x in records if x["document_id"]==document_id),None)
    if not record: raise SystemExit(f"Không tìm thấy document_id: {document_id}")
    path=Path(record["normalized_path"]); actual=hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != record["normalized_sha256"]: raise SystemExit("DOCUMENT_NOT_RESOLVED: normalized SHA mismatch")
    available={int(x["page"]) for x in pages(path.read_text(encoding="utf-8",errors="replace"))}
    labels=json.loads(labels_path.read_text(encoding="utf-8"))
    if set(labels)-set(SECTIONS): raise SystemExit("Chỉ được label 5 core sections")
    record["sections"]={name:validate_section(labels.get(name),available) for name in SECTIONS}
    record["review_status"]=status
    record["review_notes"]=labels.get("review_notes","") if isinstance(labels,dict) else ""
    GT.write_text(json.dumps(records,ensure_ascii=False,indent=2),encoding="utf-8")


def main() -> None:
    parser=argparse.ArgumentParser(description="Display pages for independent manual ground truth review")
    parser.add_argument("--document-id", required=True)
    parser.add_argument("--display", action="store_true", help="print page snippets and keyword highlights")
    parser.add_argument("--labels-file", type=Path, help="reviewer-authored JSON labels; never generated by this helper")
    parser.add_argument("--review-status", choices=("unreviewed","in_progress","reviewed","ambiguous"), default="reviewed")
    args=parser.parse_args()
    if args.display: display(args.document_id)
    if args.labels_file: save(args.document_id,args.labels_file,args.review_status)


if __name__ == "__main__": main()
